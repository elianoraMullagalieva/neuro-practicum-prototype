import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const galleryDirectory = 'assets/tunnel';
const supported = /\.(avif|gif|jpe?g|png|webp)$/i;
const files = (await readdir(galleryDirectory))
  .filter((file) => supported.test(file))
  .sort((a, b) => a.localeCompare(b, 'en'));

const manifest = `// Generated by scripts/sync-tunnel-gallery.mjs\nwindow.TUNNEL_GALLERY_IMAGES = Object.freeze(${JSON.stringify(files.map((file) => join(galleryDirectory, file)), null, 2)});\n`;
await writeFile(join(galleryDirectory, 'gallery-manifest.js'), manifest);
